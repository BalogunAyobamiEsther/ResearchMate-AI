from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """
    Schema for incoming research questions.
    """
    question: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description="The research question submitted by the user."
    )

    top_k: int = Field(
        default=5,
        ge=1,
        le=10,
        description="Number of relevant passages to retrieve."
    )


class Citation(BaseModel):
    """
    Schema for a citation attached to an answer.
    """
    source_id: str
    document_id: str
    filename: str
    page_number: int


class Evidence(BaseModel):
    """
    Schema for a retrieved research passage.
    """
    source_id: str
    chunk_id: str
    document_id: str
    filename: str
    page_number: int
    text: str


class ChatResponse(BaseModel):
    """
    Schema for the research assistant's response.
    """
    answer: str
    citations: list[Citation]
    evidence: list[Evidence]
    insufficient_evidence: bool


class LLMResponse(BaseModel):
    """
    Structured response generated by Gemini.
    """
    answer: str
    insufficient_evidence: bool